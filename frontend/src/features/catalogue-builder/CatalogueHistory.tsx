'use client';

import { useEffect, useMemo, useState } from 'react';
import { useRouter } from 'next/navigation';
import { ArrowDownToLine, Copy, Eye, FilePlus2, Pencil, Search, Trash2 } from 'lucide-react';
import { catalogueService, type CatalogueHistoryRecord } from '@/services/catalogueService';
import styles from './history.module.css';

const BUILDER_KEY = 'tile-catalogue-builder-v1';

export function CatalogueHistory() {
  const router = useRouter();
  const [entries, setEntries] = useState<CatalogueHistoryRecord[]>([]);
  const [query, setQuery] = useState('');
  const [details, setDetails] = useState<CatalogueHistoryRecord | null>(null);
  const [notice, setNotice] = useState('');
  const [loading, setLoading] = useState(true);
  const [busyId, setBusyId] = useState('');

  const refresh = async () => {
    try {
      setEntries(await catalogueService.history());
      setNotice('');
    } catch {
      setNotice('Catalogue History could not be loaded from the server. Check your connection and sign-in.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => { void refresh(); }, []);

  const filtered = useMemo(() => entries.filter((entry) =>
    `${entry.name} ${entry.generatedBy} ${entry.assignedTo}`.toLowerCase().includes(query.toLowerCase()),
  ), [entries, query]);

  const openBuilder = (entry: CatalogueHistoryRecord, duplicate = false) => {
    try {
      localStorage.setItem(BUILDER_KEY, JSON.stringify({
        ...entry.config,
        name: duplicate ? `${entry.name} copy` : entry.name,
      }));
    } catch {
      setNotice('Unable to prepare this catalogue in the builder.');
      return;
    }
    router.push('/catalogues/builder');
  };

  const remove = async (entry: CatalogueHistoryRecord) => {
    setBusyId(entry.id);
    try {
      await catalogueService.deleteHistory(entry.id);
      setEntries((current) => current.filter((item) => item.id !== entry.id));
      setDetails(null);
    } catch {
      setNotice('This history entry could not be deleted from the server.');
    } finally {
      setBusyId('');
    }
  };

  const formatDate = (value: string) => {
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return '—';
    return <span className={styles.date}><span>{date.toLocaleDateString()}</span><span>{date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' })}</span></span>;
  };

  const statusLabel = (status: CatalogueHistoryRecord['status']) => {
    if (status === 'READY') return 'Ready';
    if (status === 'FAILED') return 'Failed';
    return 'Generating…';
  };

  return <main className={styles.page}>
    <header className={styles.header}>
      <div><span className={styles.eyebrow}>CATALOGUE STUDIO</span><h1>Catalogue History</h1><p>PDF catalogue records saved to your account.</p></div>
      <button className={styles.primary} onClick={() => router.push('/catalogues/builder')}><FilePlus2 size={17}/>Create catalogue</button>
    </header>

    {notice && <div className={styles.notice} role="status">{notice}<button onClick={() => setNotice('')} aria-label="Dismiss">×</button></div>}

    <div className={styles.tools}><label><Search size={17}/><input value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Search catalogue, client or creator" aria-label="Search history"/></label><span>{filtered.length} {filtered.length === 1 ? 'catalogue' : 'catalogues'}</span></div>

    {loading ? <p className={styles.loading}>Loading Catalogue History…</p> : filtered.length ? <div className={styles.tableWrap}><table>
      <thead><tr><th>Name</th><th>Date &amp; time</th><th>Generated by</th><th>Assigned to</th><th>PDF status</th><th>Quick actions</th></tr></thead>
      <tbody>{filtered.map((entry) => <tr key={entry.id}>
        <td><button className={styles.nameButton} onClick={() => setDetails(entry)}>{entry.name}</button><span className={styles.subline}>{Array.isArray(entry.config.selected) ? `${entry.config.selected.length} designs` : 'Catalogue'}</span></td>
        <td>{formatDate(entry.createdAt)}</td><td>{entry.generatedBy || '—'}</td><td>{entry.assignedTo || '—'}</td>
        <td><span className={styles.pdfStatus}>{statusLabel(entry.status)}</span></td>
        <td><div className={styles.actions}>
          <button title="View details" aria-label={`View ${entry.name}`} onClick={() => setDetails(entry)}><Eye size={16}/></button>
          <button title="Edit catalogue" aria-label={`Edit ${entry.name}`} onClick={() => openBuilder(entry)}><Pencil size={16}/></button>
          <button title="Duplicate as a new draft" aria-label={`Duplicate ${entry.name}`} onClick={() => openBuilder(entry, true)}><Copy size={16}/></button>
          <button title="Create PDF again" aria-label={`Create PDF again for ${entry.name}`} onClick={() => openBuilder(entry)}><ArrowDownToLine size={16}/></button>
          <button title="Delete history entry" aria-label={`Delete ${entry.name}`} disabled={busyId === entry.id} onClick={() => void remove(entry)}><Trash2 size={16}/></button>
        </div></td>
      </tr>)}</tbody>
    </table></div> : <section className={styles.empty}><div className={styles.emptyIcon}><FilePlus2 size={21}/></div><h2>{entries.length ? 'No matching catalogues' : 'No catalogues generated yet'}</h2><p>{entries.length ? 'Try another search term.' : 'When you create a PDF, its record will be saved here in your account.'}</p>{!entries.length && <button onClick={() => router.push('/catalogues/builder')}>Open Catalogue Builder</button>}</section>}

    {details && <div className={styles.backdrop} role="presentation" onMouseDown={(event) => { if (event.target === event.currentTarget) setDetails(null); }}><section className={styles.dialog} role="dialog" aria-modal="true" aria-labelledby="history-detail-title"><header><div><span className={styles.eyebrow}>HISTORY DETAILS</span><h2 id="history-detail-title">{details.name}</h2></div><button className={styles.close} onClick={() => setDetails(null)} aria-label="Close">×</button></header><dl><div><dt>Date &amp; time</dt><dd>{formatDate(details.createdAt)}</dd></div><div><dt>Generated by</dt><dd>{details.generatedBy || '—'}</dd></div><div><dt>Assigned to</dt><dd>{details.assignedTo || '—'}</dd></div><div><dt>Designs</dt><dd>{Array.isArray(details.config.selected) ? details.config.selected.length : 0}</dd></div><div><dt>PDF status</dt><dd>{statusLabel(details.status)}</dd></div></dl><footer><button onClick={() => void remove(details)}><Trash2 size={16}/>Delete entry</button><button className={styles.primary} onClick={() => openBuilder(details)}><ArrowDownToLine size={16}/>Create PDF again</button></footer></section></div>}
  </main>;
}
